## Variáveis sempre em minusculo, nunca usar caracteres especiais e se possível nunca usar números



# Inteiros = int

idade = 24
print(idade, type(idade))

# Float = float

preco = 10.99
print(preco, type(preco))

# Texto = strings

nome_aluno = "Marcus"
sobrenome_aluno = "Santos"

print(nome_aluno, sobrenome_aluno, type(nome_aluno), type(sobrenome_aluno))

# Booleanos = bool

aluno_cadastrado = True
aluno_desclassificado = False

print(aluno_cadastrado, aluno_desclassificado, type(aluno_cadastrado), type(aluno_desclassificado))